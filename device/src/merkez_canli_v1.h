static const char CANLI_JS[] =
	"'use strict';\n"
	"// KÖLE Merkez v8 hızlı canlı izleme (20.10.2026, Claude). ÇEK biçimi: bir kare alınınca yenisi istenir\n"
	"// (/api/kamera/kare?son=<sıra>); yolda en çok bir kare olduğu için yavaş/aktarıcı (DERP) bağlantıda görüntü\n"
	"// birikmez, yalnız kare hızı düşer. Daha yeni kare yoksa sunucu 204 döner, 80 ms sonra yeniden sorulur.\n"
	"const $ = (s) => document.querySelector(s);\n"
	"let sira = 0;\n"
	"let calisiyor = false;\n"
	"let eskiUrl = null;\n"
	"let hataSay = 0;\n"
	"const zamanlar = [];\n"
	"\n"
	"function durum(m) { $('#durum').textContent = m; }\n"
	"\n"
	"async function istek(yol, govde) {\n"
	"  const r = await fetch(yol, {\n"
	"    method: 'POST', credentials: 'same-origin', cache: 'no-store',\n"
	"    headers: { 'Content-Type': 'application/json', 'X-Kole': '1' }, body: JSON.stringify(govde || {}),\n"
	"  });\n"
	"  const j = await r.json().catch(() => ({}));\n"
	"  if (!r.ok) { const e = new Error(j.hata || ('HTTP ' + r.status)); e.durum = r.status; throw e; }\n"
	"  return j;\n"
	"}\n"
	"\n"
	"function kapaliGoster() {\n"
	"  calisiyor = false;\n"
	"  $('#ac').hidden = false;\n"
	"  $('#kapat').hidden = true;\n"
	"  $('#bos').hidden = false;\n"
	"  $('#bos').textContent = 'Kamera kapalı';\n"
	"  durum('—');\n"
	"}\n"
	"\n"
	"function girisGoster() {\n"
	"  calisiyor = false;\n"
	"  $('#giris').hidden = false;\n"
	"  $('#ac').hidden = true;\n"
	"  durum('Oturum gerekli');\n"
	"}\n"
	"\n"
	"function baslat() {\n"
	"  if (calisiyor || document.hidden) return;\n"
	"  calisiyor = true;\n"
	"  hataSay = 0;\n"
	"  $('#ac').hidden = true;\n"
	"  $('#kapat').hidden = false;\n"
	"  cek();\n"
	"}\n"
	"\n"
	"async function cek() {\n"
	"  if (!calisiyor) return;\n"
	"  if (document.hidden) { calisiyor = false; return; }\n"
	"  const t0 = performance.now();\n"
	"  let r;\n"
	"  try {\n"
	"    r = await fetch('/api/kamera/kare?son=' + sira, { credentials: 'same-origin', cache: 'no-store' });\n"
	"  } catch (e) {\n"
	"    durum('Bağlantı yok, yeniden deneniyor…');\n"
	"    setTimeout(cek, 1000);\n"
	"    return;\n"
	"  }\n"
	"  if (r.status === 200) {\n"
	"    const b = await r.blob();\n"
	"    const t1 = performance.now();\n"
	"    sira = Number(r.headers.get('X-Seq')) || sira;\n"
	"    const yas = Number(r.headers.get('X-Yas-Ms')) || 0;\n"
	"    const kalan = Number(r.headers.get('X-Kalan-Sn')) || 0;\n"
	"    const url = URL.createObjectURL(b);\n"
	"    const img = $('#kare');\n"
	"    img.onload = () => { if (eskiUrl && eskiUrl !== url) URL.revokeObjectURL(eskiUrl); eskiUrl = url; };\n"
	"    img.src = url;\n"
	"    $('#bos').hidden = true;\n"
	"    zamanlar.push(t1);\n"
	"    while (zamanlar.length && t1 - zamanlar[0] > 5000) zamanlar.shift();\n"
	"    const fps = zamanlar.length > 1 ? (zamanlar.length - 1) * 1000 / (t1 - zamanlar[0]) : 0;\n"
	"    durum(fps.toFixed(1) + ' kare/sn · görüntü yaşı ≈ ' + Math.round(yas + (t1 - t0)) + ' ms · ' +\n"
	"      Math.round(b.size / 1024) + ' KB · ' + Math.floor(kalan / 60) + ':' + String(kalan % 60).padStart(2, '0') + ' kaldı');\n"
	"    hataSay = 0;\n"
	"    setTimeout(cek, 0);\n"
	"    return;\n"
	"  }\n"
	"  if (r.status === 204) { setTimeout(cek, 80); return; }\n"
	"  if (r.status === 401) { girisGoster(); return; }\n"
	"  if (r.status === 423) { kapaliGoster(); return; }\n"
	"  if (r.status === 409) { durum('Panelde gizlilik kalkanı açık'); setTimeout(cek, 3000); return; }\n"
	"  hataSay++;\n"
	"  durum('Hata ' + r.status + ', yeniden deneniyor…');\n"
	"  setTimeout(cek, Math.min(1000 * hataSay, 5000));\n"
	"}\n"
	"\n"
	"async function ilk() {\n"
	"  let r;\n"
	"  try {\n"
	"    r = await fetch('/api/kamera/durum', { credentials: 'same-origin', cache: 'no-store' });\n"
	"  } catch (e) {\n"
	"    durum('Merkeze ulaşılamadı, yeniden deneniyor…');\n"
	"    setTimeout(ilk, 2000);\n"
	"    return;\n"
	"  }\n"
	"  if (r.status === 401) { girisGoster(); return; }\n"
	"  const j = await r.json().catch(() => ({}));\n"
	"  if (j.acik) baslat(); else kapaliGoster();\n"
	"}\n"
	"\n"
	"$('#ac').addEventListener('submit', async (e) => {\n"
	"  e.preventDefault();\n"
	"  const dk = Number((e.submitter && e.submitter.dataset.dk) || 5);\n"
	"  const sifre = $('#sifre').value;\n"
	"  $('#sifre').value = '';\n"
	"  $('#hata').textContent = '';\n"
	"  try {\n"
	"    await istek('/api/kamera/ac', { sifre, dakika: dk });\n"
	"    $('#bos').textContent = 'Bağlanıyor…';\n"
	"    baslat();\n"
	"  } catch (err) {\n"
	"    if (err.durum === 401) girisGoster();\n"
	"    else $('#hata').textContent = err.message;\n"
	"  }\n"
	"});\n"
	"\n"
	"$('#kapat').addEventListener('click', async () => {\n"
	"  calisiyor = false;\n"
	"  await istek('/api/kamera/kapat', {}).catch(() => {});\n"
	"  kapaliGoster();\n"
	"});\n"
	"\n"
	"$('#tam').addEventListener('click', () => {\n"
	"  const s = $('#sahne');\n"
	"  if (document.fullscreenElement) document.exitFullscreen();\n"
	"  else if (s.requestFullscreen) s.requestFullscreen();\n"
	"  else if (s.webkitRequestFullscreen) s.webkitRequestFullscreen();\n"
	"});\n"
	"\n"
	"document.addEventListener('visibilitychange', () => {\n"
	"  if (document.hidden) calisiyor = false;\n"
	"  else ilk();\n"
	"});\n"
	"\n"
	"ilk();\n";

